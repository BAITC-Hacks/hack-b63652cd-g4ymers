export type TourProgress = { version: 2; step: number; status: "in-progress" | "dismissed" | "completed" };
export type TourStorage = Pick<Storage, "getItem" | "setItem">;
export const tourStorageKey = (userId: string) => `citizen-onboarding:v2:${userId}`;
export const initialTourProgress = (): TourProgress => ({ version: 2, step: 0, status: "in-progress" });

export function readTourProgress(storage: TourStorage | null, userId: string): TourProgress | null {
  try {
    const value: unknown = JSON.parse(storage?.getItem(tourStorageKey(userId)) ?? "null");
    if (!value || typeof value !== "object") return null;
    const data = value as Partial<TourProgress>;
    if (data.version !== 2 || !Number.isInteger(data.step) || data.step! < 0 || data.step! >= tourSteps.length ||
      !["in-progress", "dismissed", "completed"].includes(data.status ?? "")) return null;
    return data as TourProgress;
  } catch { return null; }
}

export function saveTourProgress(storage: TourStorage | null, userId: string, progress: TourProgress) {
  try { storage?.setItem(tourStorageKey(userId), JSON.stringify(progress)); } catch { /* Private mode / full storage: keep in-memory state. */ }
}
